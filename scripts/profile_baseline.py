#!/usr/bin/env python3
"""Measure how the upstream miner's cost grows with conjunction depth.

Evidence for docs/01-problem.md, Issues 4 and 6.

For each Galaxy subset size and each depth, it runs the *unmodified* upstream
miner (frequent mining only) in a fresh PeTTa process and records wall time,
the number of patterns printed, and the number of *distinct* patterns
(clause-order duplicates merged by minerllm.patterns.canonical). Every printed
support is also checked against the independent oracle.

Usage:  python3 scripts/profile_baseline.py [--sizes 200 400] [--depths 0 1] [--append]
Output: docs/evidence/baseline-profile.{csv,md}
"""
from __future__ import annotations

import argparse
import csv
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from minerllm.config import MinerConfig  # noqa: E402
from minerllm.datasets import galaxy_subset  # noqa: E402
from minerllm.harness import run_upstream  # noqa: E402

WORK = ROOT / "_generated" / "profile"
OUT = ROOT / "docs" / "evidence"
FIELDS = ["atoms", "depth", "conjuncts", "minsup", "seconds", "printed", "distinct",
          "oracle_checked", "oracle_mismatches", "status"]
INTS = {"atoms", "depth", "conjuncts", "minsup", "printed", "distinct",
        "oracle_checked", "oracle_mismatches"}


def load_rows(path: Path) -> list[dict]:
    if not path.exists():
        return []
    with open(path) as f:
        return [{k: (int(v) if k in INTS else float(v) if k == "seconds" else v)
                 for k, v in r.items()} for r in csv.DictReader(f)]


def write_outputs(rows: list[dict]) -> None:
    rows.sort(key=lambda r: (r["atoms"], r["depth"]))
    with open(OUT / "baseline-profile.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=FIELDS)
        w.writeheader()
        w.writerows(rows)
    lines = ["| atoms | conjuncts | minsup | time (s) | printed | distinct | duplicates | "
             "supports = oracle | status |",
             "|---:|---:|---:|---:|---:|---:|---:|---|---|"]
    for r in rows:
        dup = 1 - r["distinct"] / r["printed"] if r["printed"] else 0
        oracle = ("✅ " if r["oracle_mismatches"] == 0 else "❌ ") + \
                 f"{r['oracle_checked'] - r['oracle_mismatches']}/{r['oracle_checked']}"
        lines.append(f"| {r['atoms']} | {r['conjuncts']} | {r['minsup']} | {r['seconds']} | "
                     f"{r['printed']} | {r['distinct']} | {dup:.0%} | {oracle} | {r['status']} |")
    (OUT / "baseline-profile.md").write_text(
        "# Baseline profile: upstream miner on Galaxy subsets\n\n"
        "Generated by `make profile` (scripts/profile_baseline.py). Frequent mining only, "
        "unmodified upstream code, pinned PeTTa, one fresh process per row.\n\n"
        "* **printed**: `supportOf` lines the miner outputs\n"
        "* **distinct**: after merging clause-order / variable-name duplicates\n"
        "* **supports = oracle**: printed supports that match the independent Python "
        "counter (`minerllm/oracle.py`)\n\n" + "\n".join(lines) + "\n")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--sizes", type=int, nargs="+", default=[200, 400, 600])
    ap.add_argument("--depths", type=int, nargs="+", default=[0, 1])
    ap.add_argument("--minsup", type=int, default=5)
    ap.add_argument("--timeout", type=int, default=900)
    ap.add_argument("--append", action="store_true",
                    help="add rows to the existing CSV instead of replacing it")
    args = ap.parse_args()

    OUT.mkdir(parents=True, exist_ok=True)
    rows = load_rows(OUT / "baseline-profile.csv") if args.append else []
    for n in args.sizes:
        data = galaxy_subset(n, WORK)
        for d in args.depths:
            cfg = MinerConfig(dataset=str(data), minsup=args.minsup, depth=d,
                              surp_mode="none", timeout=args.timeout)
            run, ver = run_upstream(cfg, WORK / "runs", label=f"galaxy_{n}_d{d}")
            printed = len(re.findall(r"^\(supportOf ", run.stdout, re.M))
            row = dict(atoms=n, depth=d, conjuncts=d + 2, minsup=args.minsup,
                       seconds=round(run.seconds, 1), printed=printed,
                       distinct=len(run.patterns), oracle_checked=ver.checked,
                       oracle_mismatches=len(ver.mismatches),
                       status="ok" if run.ok else ("timeout" if run.timed_out else "error"))
            rows = [r for r in rows if (r["atoms"], r["depth"]) != (n, d)] + [row]
            print(row, flush=True)
    write_outputs(rows)
    print(f"\nWrote {OUT / 'baseline-profile.md'}")


if __name__ == "__main__":
    main()
