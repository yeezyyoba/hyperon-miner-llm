#!/usr/bin/env python3
"""Measure how the upstream miner's cost grows with conjunction depth.

Evidence for docs/01-problem.md, Issue 6 (the problem the LLM targets).

For each Galaxy subset size and each depth, it runs the *unmodified* upstream
miner (frequent mining only, minsup 5) in a fresh PeTTa process and records
wall time and the number of patterns returned. Results go to
docs/evidence/baseline-profile.{csv,md}.

Usage:  python3 scripts/profile_baseline.py [--sizes 200 400 600] [--depths 0 1]
"""
from __future__ import annotations

import argparse
import csv
import os
import random
import re
import subprocess
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MINER = ROOT / "external" / "hyperon-miner"
GALAXY = MINER / "experiments" / "data" / "galaxy_data_full.metta"
WORK = ROOT / "_generated" / "profile"
OUT = ROOT / "docs" / "evidence"
ANSI = re.compile(r"\x1b\[[0-9;]*m")

TEMPLATE = (ROOT / "run_miner.metta").read_text()


def galaxy_subset(n: int, seed: int = 7) -> Path:
    """Deterministic random sample of n relation atoms (type declarations dropped)."""
    rels = [l for l in GALAXY.read_text().splitlines()
            if l.startswith("(") and not l.startswith("(:")]
    sample = sorted(random.Random(seed).sample(rels, n))
    path = WORK / f"galaxy_{n}.metta"
    path.write_text("\n".join(sample) + "\n")
    return path


def make_script(data: Path, minsup: int, depth: int) -> Path:
    src = TEMPLATE.replace("external/", str(ROOT / "external") + "/")
    src = re.sub(r"!\(import! &db .*\)", f"!(import! &db {data.with_suffix('')})", src)
    src = re.sub(r"!\(pattern-miner &res .*\)",
                 f"!(pattern-miner &res &db $x {minsup} {depth} none none none True)", src)
    path = WORK / f"run_{data.stem}_d{depth}.metta"
    path.write_text(src)
    return path


def run(script: Path, timeout: int) -> tuple[str, float, int]:
    env = dict(os.environ, LANG="C.UTF-8", LC_ALL="C.UTF-8")
    start = time.time()
    try:
        proc = subprocess.run(["bash", str(ROOT / ".petta" / "run.sh"), str(script)],
                              capture_output=True, text=True, timeout=timeout, env=env)
    except subprocess.TimeoutExpired:
        return "timeout", float(timeout), -1
    secs = time.time() - start
    out = ANSI.sub("", proc.stdout)
    n = len(re.findall(r"^\(supportOf ", out, re.M))
    return ("ok" if proc.returncode == 0 else f"exit {proc.returncode}"), secs, n


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--sizes", type=int, nargs="+", default=[200, 400, 600])
    ap.add_argument("--depths", type=int, nargs="+", default=[0, 1])
    ap.add_argument("--minsup", type=int, default=5)
    ap.add_argument("--timeout", type=int, default=900)
    ap.add_argument("--append", action="store_true",
                    help="add rows to the existing CSV instead of replacing it")
    args = ap.parse_args()

    WORK.mkdir(parents=True, exist_ok=True)
    OUT.mkdir(parents=True, exist_ok=True)
    rows = []
    csv_path = OUT / "baseline-profile.csv"
    if args.append and csv_path.exists():
        with open(csv_path) as f:
            rows = [{k: (int(v) if k in ("atoms", "depth", "conjuncts", "minsup", "patterns")
                         else float(v) if k == "seconds" else v) for k, v in r.items()}
                    for r in csv.DictReader(f)]
    for n in args.sizes:
        data = galaxy_subset(n)
        for d in args.depths:
            status, secs, count = run(make_script(data, args.minsup, d), args.timeout)
            row = dict(atoms=n, depth=d, conjuncts=d + 2, minsup=args.minsup,
                       seconds=round(secs, 1), patterns=count, status=status)
            rows.append(row)
            print(row, flush=True)

    rows.sort(key=lambda r: (r["atoms"], r["depth"]))
    with open(csv_path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)

    lines = ["| atoms | conjuncts | minsup | time (s) | patterns | status |",
             "|---:|---:|---:|---:|---:|---|"]
    lines += [f"| {r['atoms']} | {r['conjuncts']} | {r['minsup']} | {r['seconds']} | "
              f"{r['patterns'] if r['patterns'] >= 0 else '–'} | {r['status']} |" for r in rows]
    (OUT / "baseline-profile.md").write_text(
        "# Baseline profile: upstream miner on Galaxy subsets\n\n"
        "Generated by `make profile` (scripts/profile_baseline.py). Frequent mining only, "
        "unmodified upstream code, pinned PeTTa, one fresh process per row.\n\n"
        + "\n".join(lines) + "\n")
    print(f"\nWrote {OUT / 'baseline-profile.md'}")


if __name__ == "__main__":
    main()
